#!/usr/bin/env python3
"""
apply_curriculum_resources.py - Inject structured resources into curriculum data files for A2, B1, B2, C1, and C2.
"""

import os
import sys
import pprint
from resources_data_builder import (
    get_a2_resources,
    get_b1_resources,
    get_b2_resources,
    get_c1_resources,
    get_c2_resources
)

LEVEL_CONFIGS = [
    ("French_A2", "a2_curriculum_data.py", "A2_PAGES_DATA", get_a2_resources()),
    ("French_B1", "b1_curriculum_data.py", "B1_PAGES_DATA", get_b1_resources()),
    ("French_B2", "b2_curriculum_data.py", "B2_PAGES_DATA", get_b2_resources()),
    ("French_C1", "c1_curriculum_data.py", "C1_PAGES_DATA", get_c1_resources()),
    ("French_C2", "c2_curriculum_data.py", "C2_PAGES_DATA", get_c2_resources()),
]

def update_curriculum(level_dir, filename, dict_name, resources_dict):
    filepath = os.path.join(level_dir, filename)
    print(f"Updating {filepath}...")
    
    # Load current module
    sys.path.insert(0, level_dir)
    mod_name = filename[:-3]
    if mod_name in sys.modules:
        del sys.modules[mod_name]
    mod = __import__(mod_name)
    pages_data = getattr(mod, dict_name)
    
    # Inject pages 53 to 67
    for p_num, p_data in resources_dict.items():
        pages_data[p_num] = p_data
        
    # Write back clean python file
    content = f"# Autogenerated and curated curriculum data for {level_dir}\n\n"
    content += f"{dict_name} = " + pprint.pformat(pages_data, width=120, sort_dicts=False) + "\n"
    
    with open(filepath, "w", encoding="utf-8") as f:
        f.write(content)
        
    print(f"Successfully updated {filepath}: pages 53-67 now contain structured resources.")
    sys.path.pop(0)

def main():
    for level_dir, filename, dict_name, res_dict in LEVEL_CONFIGS:
        update_curriculum(level_dir, filename, dict_name, res_dict)

if __name__ == "__main__":
    main()
